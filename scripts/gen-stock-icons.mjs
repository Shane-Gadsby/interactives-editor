//Reads the Toolbox's own Icon Set (toolbox/public/images/icons/SDC__Icon_*.svg, named by toolbox/public/sys/js/icons.js)
//and writes src/lib/stock-icons-data.ts: the path data of each icon, nothing else. The files are two-tone, a ring
//(class toolbox-icon-style-1) and a glyph (style-2), on a 32 by 32 board. Run it again if the Toolbox's icons change:
//  node scripts/gen-stock-icons.mjs [path to the toolbox repo]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const toolbox = path.resolve(process.argv[2] ?? path.join(here, '..', '..', 'toolbox'));
const dir = path.join(toolbox, 'public', 'images', 'icons');
const titles = fs.readFileSync(path.join(toolbox, 'public', 'sys', 'js', 'icons.js'), 'utf8');

//What the Toolbox's picker calls each one, by file
const nameOf = {};
for (const m of titles.matchAll(/title:\s*'([^']+)'[\s\S]*?src:\s*'images\/icons\/(SDC__Icon_[A-Za-z_]+\.svg)'/g)) nameOf[m[2]] = m[1];

//Plain words people look an icon up by, beyond its name (written from what each one draws)
const WORDS = {
  Alarm: 'bell alert reminder notification ring deadline',
  Assessment: 'tick check mark done correct test exam quiz assignment',
  Attachment: 'paperclip paper clip file attach',
  Audio: 'microphone mic record recording voice podcast sound',
  Calendar: 'date dates schedule week timetable diary',
  Chevron: 'arrow next forward right more go',
  'Discuss/ Communicate': 'speech bubble chat talk conversation forum message comment say',
  Download: 'save arrow tray get file',
  Important: 'exclamation mark warning notice attention alert',
  Info: 'information about i help detail',
  'Learning Activity': 'star activity task practice exercise favourite',
  Link: 'chain url hyperlink connect web address',
  Listen: 'speaker volume sound loud audio hear',
  Love: 'heart like favourite care',
  Mail: 'email envelope letter message inbox contact',
  Milestone: 'flag goal marker checkpoint finish achievement',
  Person: 'people user profile avatar student teacher account',
  Question: 'question mark help ask query quiz',
  Read: 'document page file text reading notes paper',
  Search: 'magnifying glass magnifier find look zoom',
  Think: 'light bulb lightbulb idea reflect thought tip',
  'Thumbs Up': 'like good approve yes agree ok',
  Time: 'clock hour minutes duration timer watch',
  Watch: 'play video triangle start view movie',
  Write: 'pencil pen edit draft note author',
};

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const rectD = (a) => {
  const n = (k) => parseFloat(a[k] ?? '0');
  const x = n('x'), y = n('y'), w = n('width'), h = n('height'), rx = n('rx'), ry = n('ry') || rx;
  const f = (v) => +v.toFixed(4);
  if (!rx) return `M${f(x)} ${f(y)}H${f(x + w)}V${f(y + h)}H${f(x)}Z`;
  return `M${f(x + rx)} ${f(y)}H${f(x + w - rx)}A${f(rx)} ${f(ry)} 0 0 1 ${f(x + w)} ${f(y + ry)}V${f(y + h - ry)}A${f(rx)} ${f(ry)} 0 0 1 ${f(x + w - rx)} ${f(y + h)}H${f(x + rx)}A${f(rx)} ${f(ry)} 0 0 1 ${f(x)} ${f(y + h - ry)}V${f(y + ry)}A${f(rx)} ${f(ry)} 0 0 1 ${f(x + rx)} ${f(y)}Z`;
};
const attrsOf = (s) => Object.fromEntries([...s.matchAll(/([\w:-]+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

const out = [];
for (const file of fs.readdirSync(dir).filter((f) => /^SDC__Icon_.*\.svg$/.test(f)).sort()) {
  const svg = fs.readFileSync(path.join(dir, file), 'utf8');
  const title = nameOf[file] ?? file.replace(/^SDC__Icon_/, '').replace(/\.svg$/, '').replace(/_/g, ' ');
  const ring = [];
  const glyph = [];
  for (const m of svg.matchAll(/<(path|rect)\b([^>]*?)\/?>/gs)) {
    const a = attrsOf(m[2]);
    const d = (m[1] === 'path' ? a.d : rectD(a)).replace(/\s+/g, ' ').trim();
    if ((a.class ?? '').includes('toolbox-icon-style-1')) ring.push(d);
    else if ((a.class ?? '').includes('toolbox-icon-style-2')) glyph.push(d);
    else throw new Error(`${file}: a shape with no style class`);
  }
  if (!ring.length || !glyph.length) throw new Error(`${file}: expected a ring and a glyph`);
  out.push({ id: slug(title), title, words: WORDS[title] ?? '', file, ring, glyph });
}

const body = out.map((i) => `  ${JSON.stringify({ id: i.id, title: i.title, words: i.words, ring: i.ring, glyph: i.glyph })},`).join('\n');
fs.writeFileSync(
  path.join(here, '..', 'src', 'lib', 'stock-icons-data.ts'),
  `//Generated by scripts/gen-stock-icons.mjs from the Toolbox's Icon Set (${out.length} icons). Do not edit by hand.
//Each icon is a 32 by 32 board with a ring and a glyph, as SVG path data.
export interface StockIconData {
  id: string;
  title: string;
  /** Other words people look it up by. */
  words: string;
  ring: string[];
  glyph: string[];
}

export const STOCK_ICON_BOARD = 32;

export const STOCK_ICON_DATA: StockIconData[] = [
${body}
];
`,
);
console.log(`${out.length} icons written`);
